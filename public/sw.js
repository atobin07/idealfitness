// Minimal, safe service worker: enables PWA install and caches static assets
// (stale-while-revalidate). HTML documents and API/auth requests are left to
// the network so nothing authenticated is ever served from cache.
const CACHE = "ideal-static-v1";
const ASSET_DESTINATIONS = ["style", "script", "image", "font"];

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }
  if (url.origin !== self.location.origin) return;
  if (!ASSET_DESTINATIONS.includes(request.destination)) return; // docs/api → network only

  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const cached = await cache.match(request);
      const network = fetch(request)
        .then((res) => {
          if (res && res.status === 200) cache.put(request, res.clone());
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
